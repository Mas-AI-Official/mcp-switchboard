/**
 * dshpatch.ts: register MCP Switchboard in a DeepSeek Harness (dsh) profile (design 3.13).
 *
 * A dsh profile is a stack of layers; the user's own layer is `<DSH_HOME>/profiles/<profile>/cordis.patch.yml`, "a
 * top-level YAML array of loader patch entries" (the file's own header). An `insert` patch "appends entries,
 * optionally inside the group identified by id" (dsh --dump-config-schema), and the MCP client plugin is
 * `@deepseek-ai/dsh-mcp-client` with `config: { serverName, transport: stdio | streamable-http, command, args | url,
 * headers }` (that package's README). So the entry is one root-level `insert` row:
 *
 *   - insert:
 *       - id: switchboard
 *         name: "@deepseek-ai/dsh-mcp-client"
 *         config: { serverName: switchboard, transport: stdio, command: <node>, args: [<cli.js>, bridge, --client, dsh] }
 *
 * The file may hold blocks written by other tools, fenced by `# BEGIN <name> (generated by ...)` and `# END <name>`
 * (observed: `local-llama`, produced by dsh_local_setup.py, "edit the script, not this block"). Anything inside one
 * is rewritten by that script, so this module never writes there. Its own row sits at the end of the file between
 * two marker comments of a different spelling (`# switchboard:begin` and `# switchboard:end`), so it can be found
 * again to be replaced or removed, and so a reader that looks for BEGIN/END pairs never mistakes it for a
 * generated block.
 *
 * Editing is text surgery on whole lines (comments and every other entry stay byte for byte); the `yaml` package
 * (already a dependency) validates the file before and after.
 */

import { LineCounter, isMap, isScalar, isSeq, parseDocument, stringify, type Document } from "yaml";
import { InstallRefusal } from "./installerror.js";

export const DSH_MCP_PLUGIN = "@deepseek-ai/dsh-mcp-client";
const MARK_BEGIN = "# switchboard:begin";
const MARK_END = "# switchboard:end";
const GEN_BEGIN = /^\s*#\s*BEGIN\s+([^\s(]+)/;
const GEN_END = /^\s*#\s*END\s+([^\s(]+)/;
const OUR_BEGIN = /^\s*# switchboard:begin(\s|$)/;
const OUR_END = /^\s*# switchboard:end\s*$/;

export interface DshSpec {
  /** The dsh serverName and entry id. */
  name: string;
  mode: "bridge" | "http";
  command: string;
  args: string[];
  url: string;
}

export interface DshLayout {
  eol: string;
  lines: string[];
  generated: { name: string; start: number; end: number }[];
  ours: { start: number; end: number } | null;
}

const NEW_FILE_HEADER = ["# Your patch layer for this dsh profile, applied after every bundle layer:", "# a top-level YAML array of loader patch entries."];

/** Split into lines (no terminators) and remember the line ending style; a trailing newline gives no extra empty line. */
function splitLines(text: string): { eol: string; lines: string[] } {
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const lines = text.split(/\r?\n/);
  if (lines.length > 0 && lines[lines.length - 1] === "") lines.pop();
  return { eol, lines };
}

export function dshLayout(text: string): DshLayout {
  const { eol, lines } = splitLines(text.charCodeAt(0) === 0xfeff ? text.slice(1) : text);
  const generated: DshLayout["generated"] = [];
  let ours: DshLayout["ours"] = null;
  let openGen: { name: string; start: number } | null = null;
  let openOurs = -1;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!;
    if (OUR_BEGIN.test(line)) {
      if (openGen) throw new InstallRefusal(`the switchboard marker at line ${i + 1} sits inside the generated block '${openGen.name}' (line ${openGen.start + 1}); that block is rewritten by its own script`);
      if (openOurs >= 0 || ours) throw new InstallRefusal(`more than one '${MARK_BEGIN}' marker (line ${i + 1}); remove the extra copy by hand`);
      openOurs = i;
      continue;
    }
    if (OUR_END.test(line)) {
      if (openOurs < 0) throw new InstallRefusal(`'${MARK_END}' at line ${i + 1} has no '${MARK_BEGIN}' before it`);
      ours = { start: openOurs, end: i };
      openOurs = -1;
      continue;
    }
    const b = GEN_BEGIN.exec(line);
    if (b) {
      if (openGen) throw new InstallRefusal(`generated block '${b[1]}' starts at line ${i + 1} inside the unfinished block '${openGen.name}' (line ${openGen.start + 1}); cannot tell where the generated text ends`);
      openGen = { name: b[1]!, start: i };
      continue;
    }
    const e = GEN_END.exec(line);
    if (e) {
      if (!openGen) throw new InstallRefusal(`'# END ${e[1]}' at line ${i + 1} has no matching '# BEGIN' before it; cannot tell where generated text lies`);
      if (openGen.name !== e[1]) throw new InstallRefusal(`'# END ${e[1]}' at line ${i + 1} does not match '# BEGIN ${openGen.name}' (line ${openGen.start + 1})`);
      generated.push({ name: openGen.name, start: openGen.start, end: i });
      openGen = null;
    }
  }
  if (openGen) throw new InstallRefusal(`generated block '${openGen.name}' (line ${openGen.start + 1}) has no '# END ${openGen.name}'; cannot tell where the generated text ends`);
  if (openOurs >= 0) throw new InstallRefusal(`'${MARK_BEGIN}' at line ${openOurs + 1} has no '${MARK_END}'; remove it by hand`);
  return { eol, lines, generated, ours };
}

function parsePatchFile(text: string): { doc: Document.Parsed; lc: LineCounter } {
  const lc = new LineCounter();
  const doc = parseDocument(text.charCodeAt(0) === 0xfeff ? text.slice(1) : text, { lineCounter: lc });
  if (doc.errors.length > 0) {
    const e = doc.errors[0]!;
    throw new InstallRefusal(`the file is not valid YAML (${e.code}: ${e.message.split("\n")[0]}); fix or move it first`);
  }
  // `!!js` expressions (the dsh dialect) only produce warnings in this parser: they are values to it, which is all we need.
  return { doc, lc };
}

/** Line (zero-based) of a node's start. */
const nodeLine = (lc: LineCounter, node: unknown): number => {
  const r = (node as { range?: [number, number, number] } | null)?.range;
  return r ? lc.linePos(r[0]).line - 1 : -1;
};

interface FoundRow {
  line: number;
  config: Record<string, unknown> | null;
  rowName: unknown;
}

/** Every root-level entry or `insert` row whose id is `id`: where it is and what it says. */
function findRows(doc: Document.Parsed, lc: LineCounter, id: string): FoundRow[] {
  const out: FoundRow[] = [];
  const root = doc.contents;
  if (!isSeq(root)) return out;
  const consider = (map: unknown): void => {
    if (!isMap(map)) return;
    const idNode = map.get("id", true);
    if (isScalar(idNode) && idNode.value === id) {
      const cfg = map.toJSON() as { config?: Record<string, unknown>; name?: unknown };
      out.push({ line: nodeLine(lc, map), config: cfg.config && typeof cfg.config === "object" ? cfg.config : null, rowName: cfg.name });
    }
  };
  for (const item of root.items) {
    consider(item);
    if (isMap(item)) {
      const ins = item.get("insert", true);
      if (isSeq(ins)) for (const row of ins.items) consider(row);
    }
  }
  return out;
}

const hasControl = (s: string): boolean => /[\u0000-\u001f\u007f]/.test(s);

/** The lines of the managed block (markers included, no line terminators). */
export function renderDshBlock(spec: DshSpec): string[] {
  for (const v of [spec.name, spec.command, spec.url, ...spec.args]) {
    if (hasControl(v)) throw new InstallRefusal("a value for the dsh entry contains a control character");
  }
  const ys = (v: string): string => stringify(v, { lineWidth: 0 }).trim();
  const L: string[] = [];
  L.push(`${MARK_BEGIN} id=${spec.name} (written by \`switchboard install dsh\`; \`switchboard uninstall dsh\` removes it)`);
  L.push("- insert:");
  L.push(`    - id: ${ys(spec.name)}`);
  L.push(`      name: ${ys(DSH_MCP_PLUGIN)}`);
  L.push("      config:");
  L.push(`        serverName: ${ys(spec.name)}`);
  if (spec.mode === "bridge") {
    L.push("        transport: stdio");
    L.push(`        command: ${ys(spec.command)}`);
    L.push("        args:");
    for (const a of spec.args) L.push(`          - ${ys(a)}`);
  } else {
    L.push("        transport: streamable-http");
    L.push(`        url: ${ys(spec.url)}`);
    L.push("        headers:");
    // The package README's own form for a bearer token read from the environment (a `!!js` expression).
    L.push("          Authorization: !!js '`Bearer ${process.env.SWITCHBOARD_TOKEN}`'");
  }
  L.push(MARK_END);
  return L;
}

export interface DshState {
  layout: DshLayout;
  /** The managed block as it is now (null: none). */
  current: string[] | null;
  /** A row with this id exists that this tool did not write (line, zero-based). */
  unmanagedLine: number | null;
}

/** Validate the file and report the managed block and any foreign row with the same id. Throws InstallRefusal when the file cannot be edited safely. */
export function inspectDshPatch(text: string, name: string): DshState {
  const layout = dshLayout(text);
  const { doc, lc } = parsePatchFile(text);
  const root = doc.contents;
  if (root !== null && !isSeq(root)) throw new InstallRefusal("the file is not a top-level YAML list of patch entries; fix or move it first");
  const rows = findRows(doc, lc, name);
  const inOurs = (line: number): boolean => !!layout.ours && line >= layout.ours.start && line <= layout.ours.end;
  const foreign = rows.find((r) => !inOurs(r.line));
  const inGenerated = rows.find((r) => layout.generated.some((g) => r.line >= g.start && r.line <= g.end));
  if (inGenerated) throw new InstallRefusal(`an entry with id '${name}' exists inside a generated block (line ${inGenerated.line + 1}); it is rewritten by its own script, so this tool will not touch it`);
  return {
    layout,
    current: layout.ours ? layout.lines.slice(layout.ours.start, layout.ours.end + 1) : null,
    unmanagedLine: foreign ? foreign.line : null,
  };
}

function assemble(layout: DshLayout, lines: string[]): string {
  return lines.join(layout.eol) + layout.eol;
}

/** Drop a flow-style empty list (`[]`) that stands alone on a line, so block entries can follow. */
function dropEmptyFlowList(text: string, layout: DshLayout): DshLayout {
  const { doc } = parsePatchFile(text);
  const root = doc.contents;
  if (!isSeq(root) || !root.flow) return layout;
  if (root.items.length > 0) throw new InstallRefusal("the file's list is written in flow style ([ ... ]); convert it to block style first");
  const idx = layout.lines.findIndex((l) => l.trim() === "[]");
  if (idx < 0) throw new InstallRefusal("the file's list is written in flow style; convert it to block style first");
  const lines = layout.lines.slice();
  lines.splice(idx, 1);
  return { ...layout, lines };
}

/** The file after the managed block is added or replaced. `existing` null: a new file. Throws InstallRefusal. */
export function upsertDshPatch(existing: string | null, spec: DshSpec): { text: string; changed: boolean } {
  const source = existing ?? NEW_FILE_HEADER.join("\n") + "\n";
  const state = inspectDshPatch(source, spec.name);
  if (state.unmanagedLine !== null) {
    throw new InstallRefusal(
      `${existing === null ? "the file" : "it"} already has an entry with id '${spec.name}' (line ${state.unmanagedLine + 1}) that this tool did not write; ` +
        "remove it or rename it first, so there is exactly one",
    );
  }
  let layout = state.layout;
  const block = renderDshBlock(spec);
  let lines: string[];
  if (layout.ours) {
    lines = layout.lines.slice();
    lines.splice(layout.ours.start, layout.ours.end - layout.ours.start + 1, ...block);
  } else {
    layout = dropEmptyFlowList(source, layout);
    lines = layout.lines.slice();
    while (lines.length > 0 && lines[lines.length - 1]!.trim() === "") lines.pop();
    if (lines.length > 0) lines.push("");
    lines.push(...block);
  }
  const text = assemble(layout, lines);
  const verdict = verifyDshPatch(text, spec);
  if (!verdict.ok) throw new InstallRefusal(`the edited file would not validate (${verdict.reason}); nothing was written`);
  return { text, changed: existing === null || text !== existing };
}

/** The file with the managed block removed. */
export function removeDshPatch(text: string, name: string): { text: string; removed: boolean; unmanagedLine: number | null } {
  const state = inspectDshPatch(text, name);
  const layout = state.layout;
  if (!layout.ours) return { text, removed: false, unmanagedLine: state.unmanagedLine };
  const lines = layout.lines.slice();
  lines.splice(layout.ours.start, layout.ours.end - layout.ours.start + 1);
  const at = layout.ours.start;
  // One blank separator line goes with the block.
  if (at > 0 && lines[at - 1]!.trim() === "" && (at >= lines.length || lines[at]!.trim() === "")) lines.splice(at - 1, 1);
  const out = lines.length > 0 ? assemble(layout, lines) : "";
  return { text: out, removed: true, unmanagedLine: state.unmanagedLine };
}

/** Parse the file again and check the entry is there, says what `spec` says, and lies outside every generated block. */
export function verifyDshPatch(text: string, spec: DshSpec): { ok: boolean; reason?: string } {
  let state: DshState;
  let doc: Document.Parsed;
  let lc: LineCounter;
  try {
    state = inspectDshPatch(text, spec.name);
    ({ doc, lc } = parsePatchFile(text));
  } catch (err) {
    return { ok: false, reason: err instanceof Error ? err.message : String(err) };
  }
  if (!state.layout.ours) return { ok: false, reason: "the managed block is missing" };
  const own = findRows(doc, lc, spec.name).filter((r) => r.line >= state.layout.ours!.start && r.line <= state.layout.ours!.end);
  if (own.length !== 1) return { ok: false, reason: `expected one entry with id '${spec.name}' inside the managed block, found ${own.length}` };
  const row = own[0]!;
  if (row.rowName !== DSH_MCP_PLUGIN) return { ok: false, reason: `the entry's plugin is not ${DSH_MCP_PLUGIN}` };
  const cfg = row.config ?? {};
  if (cfg.serverName !== spec.name) return { ok: false, reason: "serverName does not match" };
  if (spec.mode === "bridge") {
    if (cfg.transport !== "stdio" || cfg.command !== spec.command) return { ok: false, reason: "transport or command does not match" };
    if (JSON.stringify(cfg.args) !== JSON.stringify(spec.args)) return { ok: false, reason: "args do not match" };
  } else if (cfg.transport !== "streamable-http" || cfg.url !== spec.url) {
    return { ok: false, reason: "transport or url does not match" };
  }
  if (state.layout.generated.some((g) => state.layout.ours!.start >= g.start && state.layout.ours!.end <= g.end)) return { ok: false, reason: "the block sits inside a generated block" };
  return { ok: true };
}
