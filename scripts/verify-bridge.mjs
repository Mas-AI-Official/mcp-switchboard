// Deterministic oracle for the stdio bridge (design 3.12): `switchboard bridge --client <id>` and the
// client key store (src/clientkeys.ts). No model tokens, no network beyond loopback, no real client config.
//
// Three halves, all against the compiled dist/:
//   HALF A (in process) - clientkeys.ts: id validation (regex plus Windows device names), token validation,
//     write then read round trip, OS protection at rest (DPAPI on Windows, mode 0600 elsewhere), atomic
//     replace (no temp leftovers, old key survives a rejected write), and a silent stdout/stderr.
//   HALF B (real gateway) - starts the real gateway from dist on an ephemeral loopback port with
//     require_auth "always" and a temp SWITCHBOARD_HOME, mounts a tiny stdio upstream (this very file run
//     with --upstream) with one read tool, issues an API key, then spawns the REAL `node dist/cli.js bridge`
//     as a child and drives it over stdin: initialize, notifications/initialized (no output), tools/list
//     (namespaced tool), tools/call (result); wrong key and gateway down give JSON-RPC errors, never a
//     crash; the key source order is SWITCHBOARD_KEY, then --key-file, then the stored client key.
//   HALF C (header-echo server) - a local HTTP server that records every request the bridge makes and
//     answers JSON, SSE (CRLF framing, split chunks, multi-line data), HTTP errors and 202s: proves the
//     exact request headers, MCP-Protocol-Version learning, 2026-07-28 style Mcp-Method / Mcp-Name headers,
//     CRLF and fragmented and 3 MB input, large output, concurrent requests answered out of order, and a
//     clean exit (code 0) after stdin closes with requests still in flight.
// Every bridge stdout is also checked to be JSON-RPC lines only, and no token ever appears in any output.
//
// Tests never touch the operator's state: SWITCHBOARD_HOME, HOME, USERPROFILE and APPDATA are temp dirs.
// Build first: npm run build && node scripts/verify-bridge.mjs

