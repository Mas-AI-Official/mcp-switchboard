function makeEnv(extra = {}) {
  const env = { ...CHILD_ENV_BASE };
  for (const [k, v] of Object.entries(extra)) {
    if (v === undefined) delete env[k];
    else env[k] = v;
  }
  return env;
}

/** One spawned `switchboard bridge` child with line-buffered stdout capture. */
class Bridge {
  constructor(label, args, extraEnv = {}) {
    this.label = label;
    this.raw = "";
    this.err = "";
    this.partial = "";
    this.lines = [];
    this.cursor = 0;
    this.exit = null;
    this.timedOut = false;
    this.child = spawn(process.execPath, [CLI, "bridge", ...args], {
      env: makeEnv(extraEnv),
      stdio: ["pipe", "pipe", "pipe"],
      windowsHide: true,
    });
    this.child.stdout.setEncoding("utf8");
    this.child.stderr.setEncoding("utf8");
    this.child.stdout.on("data", (d) => {
      this.raw += d;
      this.partial += d;
      let i;
      while ((i = this.partial.indexOf("\n")) !== -1) {
        this.lines.push(this.partial.slice(0, i));
        this.partial = this.partial.slice(i + 1);
      }
    });
    this.child.stderr.on("data", (d) => (this.err += d));
    this.child.stdin.on("error", () => {});
    this.closed = new Promise((resolve) =>
      this.child.on("close", (code) => {
        this.exit = code;
        resolve();
      }),
    );
    bridges.push(this);
  }

  /** Send a JSON value (one line, given EOL) or a raw string/Buffer. */
  send(msg, eol = "\n") {
    this.child.stdin.write(typeof msg === "string" || Buffer.isBuffer(msg) ? msg : JSON.stringify(msg) + eol);
  }

  async next(ms = 20000) {
    const t0 = Date.now();
    while (this.cursor >= this.lines.length) {
      if (Date.now() - t0 > ms) throw new Error(`${this.label}: no output line within ${ms} ms; stderr: ${this.err.slice(-400)}`);
      await sleep(10);
    }
    const line = this.lines[this.cursor++];
    try {
      return JSON.parse(line);
    } catch {
      return { __notJson: line };
    }
  }

  /** Close stdin and wait for the child to exit by itself. */
  async finish(ms = 30000) {
    this.child.stdin.end();
    await Promise.race([this.closed, sleep(ms)]);
    if (this.exit === null) {
      this.timedOut = true;
      this.child.kill();
      await Promise.race([this.closed, sleep(3000)]);
    }
    return this;
  }

  kill() {
    try {
      this.child.kill();
    } catch {
      /* already gone */
    }
  }
}

/** The shared tail check: exit 0 on its own, stdout holds only JSON-RPC lines, nothing stray. */
function checkClean(b, expectedLines) {
  const okExit = b.exit === 0 && !b.timedOut;
  assert(`${b.label}: exits 0 by itself after stdin closes`, okExit, `exit=${b.exit} timedOut=${b.timedOut}`);
  const all = b.raw.split("\n");
  const body = all.slice(0, -1);
  const tail = all[all.length - 1];
  const parsed = body.map((l) => {
    try {
      return JSON.parse(l);
    } catch {
      return null;
    }
  });
  const onlyJsonRpc = tail === "" && parsed.every((m) => m && m.jsonrpc === "2.0") && body.every((l) => !l.endsWith("\r"));
  assert(`${b.label}: stdout carries only JSON-RPC lines`, onlyJsonRpc, onlyJsonRpc ? `${body.length} lines` : JSON.stringify(b.raw.slice(0, 200)));
  if (expectedLines !== undefined) {
    assert(`${b.label}: exactly ${expectedLines} output lines (no stray output)`, body.length === expectedLines, `got ${body.length}`);
  }
}

